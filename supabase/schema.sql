CREATE TABLE IF NOT EXISTS cycle_contributions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id BIGINT NOT NULL REFERENCES financial_cycles(id) ON DELETE CASCADE,
    participant_vault_id BIGINT NOT NULL REFERENCES vaults(id),
    income DOUBLE PRECISION NOT NULL DEFAULT 0,
    income_ratio DOUBLE PRECISION NOT NULL DEFAULT 0,

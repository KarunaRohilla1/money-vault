INSERT INTO financial_cycles (
    vault_id,
    start_date,
    end_date,
    created_at
)
SELECT
    v.id,
    (
        MAKE_DATE(mc.year, mc.month, LEAST(COALESCE(v.financial_cycle_start_day, v.month_start_day, 1), 28))
    )::text AS start_date,
    (
        MAKE_DATE(mc.year, mc.month, LEAST(COALESCE(v.financial_cycle_start_day, v.month_start_day, 1), 28))
        + INTERVAL '1 month'
        - INTERVAL '1 day'
    )::date::text AS end_date,
    mc.created_at
FROM monthly_cycles mc
JOIN vaults v
    ON v.id = mc.vault_id
ON CONFLICT (vault_id, start_date) DO NOTHING;

